/// Lightweight, typed-at-the-call-site localization used by the whole app.
///
/// Bengali is the product's primary language and English is the fallback.
/// Backend-provided course content is intentionally displayed as received.
class AppLocalizations {
  const AppLocalizations(this.locale);

  final Locale locale;

  static const supportedLocales = [Locale('bn'), Locale('en')];
  static const delegate = _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations) ??
      const AppLocalizations(Locale('bn'));

  bool get isBangla => locale.languageCode == 'bn';

  @visibleForTesting
  static Set<String> missingKeys(String languageCode) {
    final englishKeys = _translations['en']!.keys.toSet();
    final localeKeys = _translations[languageCode]?.keys.toSet() ?? const {};
    return englishKeys.difference(localeKeys);
  }

  String tr(String key, {Map<String, Object?> args = const {}}) {
    final language = _translations[locale.languageCode] ?? _translations['en']!;
    var value = language[key] ?? _translations['en']![key] ?? key;
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', '${entry.value ?? ''}');
    }
    return value;
  }

  String digits(String text) {
    if (!isBangla) return text;
    return text.replaceAllMapped(
      RegExp(r'\d'),
      (match) => const [
        '০',
        '১',
        '২',
        '৩',
        '৪',
        '৫',
        '৬',
        '৭',
        '৮',
        '৯',
      ][int.parse(match.group(0)!)],
    );
  }

  String number(num value) => digits(value.toString());

  String percent(num value) => '${number(value)}%';

